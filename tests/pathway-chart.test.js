const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
(async () => {
  const shared = `data:text/javascript;base64,${Buffer.from(fs.readFileSync(path.join(__dirname, '../site/chapters/shared.js'))).toString('base64')}`;
  const code = fs.readFileSync(path.join(__dirname, '../site/components/pathway-chart.js'), 'utf8').replace("from '../chapters/shared.js'", `from '${shared}'`);
  const { windowRows, annualRows, rangePlot, annualPlot, rowsCSV } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
  const area = { name: 'Area A', baseline_id: '1995-2014', source: { url: 'https://example.org' }, metrics: { temp: { label: 'Temperature change', unit: '°C', windows: { '2040-2059': { ssp245: { median: -1, lower: -2, upper: 0, models: 8 } } } } } };
  const rows = windowRows(area, 'temp', '2040-2059', 'Nation A');
  assert.equal(rows[0].median, -1);
  assert.equal(rows[1].median, null);
  assert.equal(rows[1].status, 'unavailable');
  assert.match(rangePlot(rows), /Unavailable/);
  assert.doesNotMatch(rangePlot(rows), /NaN/);
  area.metrics.temp.series = { ssp245: { years: [2039, 2040, 2041, 2060], median: [1, 2, 3, 4], lower: [0, 1, 2, 3], upper: [2, 3, 4, 5], models: 24 } };
  const annual = annualRows(area, 'temp', '2040-2059', 'Region A');
  assert.deepEqual(annual.filter(r => r.year).map(r => [r.year, r.median]), [[2040, 2], [2041, 3]]);
  assert.match(annualPlot(annual), /2040/);
  assert.doesNotMatch(annualPlot(annual), /NaN/);
  assert.doesNotMatch(annualPlot([{ ...annual[0], lower: null }]), /opacity=".13"/, 'missing band is not a zero edge');
  const only370 = annualPlot([{ ...annual[0], pathway_id: 'ssp370', pathway: 'SSP3-7.0' }]);
  assert.match(only370, /stroke-dasharray="8 4"/);
  assert.match(only370, /SSP3-7.0: dashed rust/);
  const csv = rowsCSV([{ ...rows[0], place: '=formula', year: 2040 }]);
  assert.match(csv, /"'=formula"/);
  assert.match(csv, /"-1"/);
  assert.match(csv, /year/);
  console.log('Pathway checks passed: exact windows and annual rows, missing pathways, shared physical scale and safe CSV.');
})().catch(error => { console.error(error); process.exitCode = 1; });
